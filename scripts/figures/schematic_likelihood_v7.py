"""Likelihood of one measurement given a candidate source (paper eq. 2), v7: the geometry is drawn on real DNS plumes.

(a, b) Instantaneous strong-forcing DNS plume at full resolution (384 x 192; run 6, plume 0, records 10 and 31 of
docs/research/data/viz/replay/strong_seed06_k287.npz, regenerated by scripts/dns2_replay.py; see dns_fullres.py),
shifted so that its source (0.8, pi) sits at (0.5, 0), cropped to x <= 3. Colour: log10 c, blank below the detection
threshold m_min = 0.01. The candidate x_j is the true source. Dashed: mean-plume edges +- sigma_y(xi) (Taylor law,
strong-forcing fit, as in the physics model); dotted: the line xi = 0 that separates upstream from downstream of x_j.
Sensor A at (1.5, 0), on the centreline of the mean plume, reads c = 2.04 at record 10 (detection) and c = 0.0023 at
record 31, 2.1 time units later (below m_min: d_k = 0): the intermittency that the likelihood models (values printed
by the script). Sensor B at (0.15, 0.25) is upstream.
(c) Probability of no detection, d_k = 0, at A and B, split into "not in plume" (1 - gamma, solid) and "in plume but
below the threshold" (gamma Phi, hatched).
(d) Density of the in-plume log-concentration z at A (solid) and B (dashed); the part below log m_min is reported as
d_k = 0 and is what (c) counts as gamma Phi.
(c, d) use the strong-forcing fitted coefficients (App. B) at l_j = -1 for A, only to make the shapes realistic.
Colour: the plume needs more levels than grey resolves (YlGnBu, sequential); sensors A and B carry two Okabe-Ito hues
(reddish purple, orange) that are also separated by line style (solid / dashed) in (d).
Run (from repo/): py -3.11 scripts/figures/schematic_likelihood_v7.py
"""
import os, sys
import numpy as np
import matplotlib.pyplot as plt
from matplotlib.patches import Patch
from scipy.stats import norm
sys.path.insert(0, os.path.dirname(__file__))
from plotstyle import use_style, panel_label, save

K, TL, S0 = 0.080, 1.60, 0.024                      # mean field (strong forcing)
L0, L1, B0, B1, S = 1.54, 0.94, -0.96, 0.40, 1.63    # in-plume branch
GL, ML, SL = 0.18, -5.22, 0.63                       # upstream of x_j (constant coefficients)
THR = np.log(1e-2)
ELL = -1.0                                           # adjoint log-mean at sensor A (illustrative)
gA, mA = 1 / (1 + np.exp(-(L0 + L1 * ELL))), B0 + B1 * ELL
CA, CB = "#CC79A7", "#E69F00"                        # sensor A, sensor B
TA, TB = "#F0D4E4", "#F9E2B3"                        # light tints of the same hues (EPS has no transparency)
FS = 9.0

use_style(base=FS)
plt.rcParams.update({"xtick.minor.visible": False, "ytick.minor.visible": False, "xtick.top": False,
                     "ytick.right": False, "hatch.linewidth": 0.7})
fig = plt.figure(figsize=(6.0, 3.6))
XL, YL = (0.0, 3.0), (-0.85, 0.85)
aw = 0.425
ah = aw * 6.0 * (YL[1] - YL[0]) / (XL[1] - XL[0]) / 3.6
axa = fig.add_axes([0.045, 0.535, aw, ah])
axb = fig.add_axes([0.505, 0.535, aw, ah])
cax = fig.add_axes([0.945, 0.535 + 0.1 * ah, 0.012, 0.8 * ah])
axc = fig.add_axes([0.09, 0.10, 0.17, 0.33])
axd = fig.add_axes([0.615, 0.10, 0.37, 0.33])

# ------------------------------------------------------------------ (a, b) real plumes
RP = np.load("docs/research/data/viz/replay/strong_seed06_k287.npz")
SX, SY = 0.8, np.pi                                  # plume 0 is released at (0.8, pi) in the DNS frame
src = np.array([0.5, 0.0])                           # ... and drawn with its source at (0.5, 0)
xg, yg = RP["x"] - SX + src[0], RP["y"] - SY + src[1]
T1, T2 = 10, 31                                      # records: A inside the instantaneous plume / outside it
pA, pB = (1.5, 0.0), (0.15, 0.25)
iA, jA = np.argmin(abs(xg - pA[0])), np.argmin(abs(yg - pA[1]))
cA1, cA2 = (float(RP["c"][t, 0, iA, jA]) for t in (T1, T2))
assert cA1 > 0.01 > cA2, (cA1, cA2)
dT = float(RP["times"][T2] - RP["times"][T1])
print(f"c_A = {cA1:.3g} (record {T1}), {cA2:.3g} (record {T2}); dt = {dT:.3g}")
xi = np.linspace(1e-3, XL[1] - src[0], 300)
r = xi / TL
sig = np.sqrt(S0 + 2 * K * TL * (r - 1 + np.exp(-r)))
for ax, t, lab, sub in [(axa, T1, "a", r"time $t$: $c_{\rm A}>m_{\min}$"),
                        (axb, T2, "b", rf"$t+{dT:.2g}$: $c_{{\rm A}}<m_{{\min}}$")]:
    c = RP["c"][t, 0].astype(np.float64)
    L = np.ma.masked_less(np.log10(np.maximum(c, 1e-30)), -2.0)
    im = ax.pcolormesh(xg, yg, L.T, cmap="YlGnBu", vmin=-2, vmax=0.8, shading="nearest", rasterized=True, zorder=-10)
    ax.plot(src[0] + xi, src[1] + sig, "k--", lw=0.9)
    ax.plot(src[0] + xi, src[1] - sig, "k--", lw=0.9)
    ax.plot([src[0], src[0]], YL, color="0.4", ls=":", lw=0.9)
    ax.plot(*src, "o", ms=8, mfc="white", mec="k", mew=1.2, zorder=3)
    ax.plot(*src, "x", ms=5.5, mec="k", mew=1.2, zorder=4)
    ax.text(src[0] - 0.05, src[1] - 0.10, r"$\boldsymbol{x}_j$", ha="right", va="top")
    for p, col, name in [(pA, CA, "A"), (pB, CB, "B")]:
        ax.plot(*p, "s", ms=6, mfc=col, mec="k", mew=0.8, zorder=5)
        dy = 0.09 if name == "A" else -0.09
        ax.text(p[0], p[1] + dy, name, ha="center", va="bottom" if dy > 0 else "top", color="k")
    ax.text(0.04, 1.02, sub, transform=ax.transAxes, ha="left", va="bottom", fontsize=FS - 0.5)
    ax.set_xlim(*XL); ax.set_ylim(*YL); ax.set_aspect("equal")
    ax.set_xticks([0, 1, 2, 3]); ax.set_yticks([-0.5, 0, 0.5])
    ax.set_xlabel(r"$x$", labelpad=1)
    panel_label(ax, lab, dx=-0.09 if lab == "a" else -0.02, dy=1.0, va="bottom")
axa.set_ylabel(r"$y$", labelpad=1)
axb.set_yticklabels([])
axa.annotate(r"mean edge", xy=(1.6, src[1] - np.interp(1.6 - src[0], xi, sig)), xytext=(1.6, -0.68), ha="center",
             va="center", fontsize=FS - 0.5,
             arrowprops=dict(arrowstyle="-", lw=0.6, color="k", shrinkA=1, shrinkB=0))
axa.annotate("", xy=(0.95, -0.62), xytext=(0.25, -0.62), arrowprops=dict(arrowstyle="-|>", lw=1.1, color="k"))
axa.text(1.02, -0.62, r"$U$", ha="left", va="center")
cb = fig.colorbar(im, cax=cax)
cb.set_ticks([-2, -1, 0])
cb.set_ticklabels([r"$\log_{10} m_{\min}$", r"$-1$", r"$0$"])
cb.ax.tick_params(direction="in", labelsize=FS - 1)
cb.set_label(r"$\log_{10} c$", labelpad=2)

# ------------------------------------------------------------------ (c) non-detection probability
cA, cB = gA * norm.cdf((THR - mA) / S), GL * norm.cdf((THR - ML) / SL)
for x, g, c_, col, tint in [(0, gA, cA, CA, TA), (1, GL, cB, CB, TB)]:
    axc.bar(x, 1 - g, width=0.62, color=col, ec="k", lw=1.0)
    axc.bar(x, c_, bottom=1 - g, width=0.62, color=tint, ec="k", lw=1.0, hatch="////")
axc.set_xticks([0, 1], [r"A", r"B"])
axc.tick_params(axis="x", length=0)
axc.set_ylim(0, 1.0); axc.set_yticks([0, 0.5, 1], [r"$0$", r"$0.5$", r"$1$"])
axc.set_xlim(-0.5, 1.5)
axc.set_ylabel(r"$p(d_k=0)$", labelpad=3)
for side in ("top", "right"):
    axc.spines[side].set_visible(False)
key = [Patch(fc="white", ec="k", hatch="////", lw=1.0, label=r"$\gamma\Phi$: in plume," "\n" r"below threshold"),
       Patch(fc="0.45", ec="k", lw=1.0, label=r"$1-\gamma$: not in plume")]
axc.legend(handles=key, loc="center left", bbox_to_anchor=(1.06, 0.55), handlelength=1.3, handleheight=1.1,
           borderaxespad=0, labelspacing=0.8, fontsize=FS)
panel_label(axc, "c", dx=-0.30, dy=1.0)

# ------------------------------------------------------------------ (d) density, one style per sensor
z = np.linspace(-9.8, 4.0, 600)
pa, pb = gA * norm.pdf(z, mA, S), GL * norm.pdf(z, ML, SL)
lo = z <= THR
axd.fill_between(z[lo], 0, pa[lo], color=TA, lw=0, zorder=-5)
axd.fill_between(z[lo], 0, pb[lo], facecolor=TB, edgecolor=CB, hatch="////", lw=0, zorder=-4)
axd.plot(z, pa, "-", color=CA, lw=1.8)
axd.plot(z, pb, "--", color=CB, lw=1.8)
axd.axvline(THR, color="k", ls=":", lw=0.9)
axd.set_xticks([THR, mA], [r"$\log m_{\min}$", r"$m_j$"])
axd.set_yticks([])
axd.set_xlim(-9.8, 4.0); axd.set_ylim(0, 0.215)
axd.set_xlabel(r"$z$", labelpad=1)
axd.set_ylabel(r"$p(z)$", labelpad=3)
for side in ("top", "right"):
    axd.spines[side].set_visible(False)
axd.text(mA + 1.25 * S, gA * norm.pdf(mA + 1.25 * S, mA, S) + 0.004, r"A", ha="left", va="bottom")
axd.text(ML - 0.75, GL * norm.pdf(ML - 0.75, ML, SL) + 0.004, r"B", ha="right", va="bottom")
axd.text(THR - 0.35, 0.212, r"in plume," "\n" r"below" "\n" r"threshold" "\n" r"($d_k = 0$)", ha="right", va="top",
         color="0.3", linespacing=1.1)
axd.text(THR + 0.35, 0.212, r"detected" "\n" r"($d_k = 1$)", ha="left", va="top", linespacing=1.1)
panel_label(axd, "d", dx=-0.06, dy=1.0)

save(fig, "figures/schematic_likelihood_v7")
print("wrote figures/schematic_likelihood_v7.{png,eps}")
